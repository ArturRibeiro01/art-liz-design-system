const colorToken = (cssVariable: string, fallback: string) => `var(${cssVariable}, ${fallback})`

const colorScaleToken = <TScale extends Record<number, string>>(
  cssVariables: Record<keyof TScale, string>,
  fallback: TScale,
) => {
  const entries = Object.entries(fallback).map(([tone, value]) => [
    Number(tone),
    colorToken(cssVariables[Number(tone) as keyof TScale], value),
  ])

  return Object.fromEntries(entries) as {
    [TKey in keyof TScale]: string
  }
}

